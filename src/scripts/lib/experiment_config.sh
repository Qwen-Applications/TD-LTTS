#!/usr/bin/env bash

LT_PROJECT_ROOT="${PROJECT_ROOT:-$(cd "$(dirname "${BASH_SOURCE[0]}")/../../.." && pwd)}"
LT_MODEL_ROOT="${LATENT_TTS_MODEL_ROOT:-${LT_PROJECT_ROOT}/model}"
LT_DATA_ROOT="${LATENT_TTS_DATA_ROOT:-${LT_PROJECT_ROOT}/dataset}"

lt_print_usage_common() {
  cat <<'USAGE'
Common options:
  --benchmark NAME        mathvista|mmstar|mmmu|logicvista|realworldqa|hallusionbench|scienceqa
  --model-family NAME     qwen3vl8b|mimovl7b|llavaov15_8b|qwen25vl32b|qwen25vl7b|qwen25vl3b|internvl3_38b|internvl35_8b|internvl35_4b|custom
  --model PATH            Override model path.
  --data PATH             Override dataset path.
  --split NAME            Override dataset split.
  --output-dir PATH       Explicit output directory.
  --start N               Start example index.
  --end N                 End example index, exclusive.
  --dry-run               Print commands without running.
USAGE
}

lt_set_model_defaults() {
  MODEL_FAMILY="${MODEL_FAMILY:-qwen25vl7b}"

  case "${MODEL_FAMILY}" in
    qwen3vl8b)
      PATH_TO_MODEL="${PATH_TO_MODEL:-${LT_MODEL_ROOT}/Qwen3-VL-8B-Instruct}"
      ;;
    mimovl7b)
      PATH_TO_MODEL="${PATH_TO_MODEL:-${LT_MODEL_ROOT}/MiMo-VL-7B-RL}"
      ;;
    llavaov15_8b)
      PATH_TO_MODEL="${PATH_TO_MODEL:-${LT_MODEL_ROOT}/LLaVA-OneVision-1.5-8B-Instruct}"
      if [[ ! -e "${PATH_TO_MODEL}" ]]; then
        PATH_TO_MODEL="lmms-lab/LLaVA-OneVision-1.5-8B-Instruct"
      fi
      ;;
    qwen25vl32b)
      PATH_TO_MODEL="${PATH_TO_MODEL:-${LT_MODEL_ROOT}/Qwen2.5-VL-32B-Instruct}"
      ;;
    qwen25vl7b)
      PATH_TO_MODEL="${PATH_TO_MODEL:-${LT_MODEL_ROOT}/Qwen2.5-VL-7B-Instruct}"
      ;;
    qwen25vl3b)
      PATH_TO_MODEL="${PATH_TO_MODEL:-${LT_MODEL_ROOT}/Qwen2.5-VL-3B-Instruct}"
      ;;
    internvl3_38b)
      PATH_TO_MODEL="${PATH_TO_MODEL:-${LT_MODEL_ROOT}/InternVL3-38B}"
      ;;
    internvl35_8b)
      PATH_TO_MODEL="${PATH_TO_MODEL:-${LT_MODEL_ROOT}/InternVL3_5-8B-Instruct}"
      ;;
    internvl35_4b)
      PATH_TO_MODEL="${PATH_TO_MODEL:-${LT_MODEL_ROOT}/InternVL3_5-4B-Instruct}"
      ;;
    custom)
      if [[ -z "${PATH_TO_MODEL:-}" ]]; then
        echo "MODEL_FAMILY=custom requires PATH_TO_MODEL or --model." >&2
        return 2
      fi
      ;;
    *)
      echo "Unknown MODEL_FAMILY: ${MODEL_FAMILY}" >&2
      return 2
      ;;
  esac

  export MODEL_FAMILY PATH_TO_MODEL
}

lt_set_benchmark_defaults() {
  if [[ -z "${BENCHMARK:-}" ]]; then
    echo "BENCHMARK is required. Use --benchmark or set BENCHMARK." >&2
    return 2
  fi

  case "${BENCHMARK}" in
    mathvista)
      PATH_TO_DATA="${PATH_TO_DATA:-${LT_DATA_ROOT}/MathVista}"
      DATASET_SPLIT="${DATASET_SPLIT:-testmini}"
      MAX_NEW_TOKENS="${MAX_NEW_TOKENS:-2048}"
      OPTIMIZED_ACCEPTANCE="${OPTIMIZED_ACCEPTANCE:-valid_prediction_mc_letter}"
      ANSWER_FINALIZER_MODE="${ANSWER_FINALIZER_MODE:-when_needed}"
      ANSWER_FINALIZER_MAX_NEW_TOKENS="${ANSWER_FINALIZER_MAX_NEW_TOKENS:-64}"
      LT_BENCHMARK_TOTAL=1000
      ;;
    mmstar)
      PATH_TO_DATA="${PATH_TO_DATA:-${LT_DATA_ROOT}/MMStar}"
      DATASET_SPLIT="${DATASET_SPLIT:-val}"
      MAX_NEW_TOKENS="${MAX_NEW_TOKENS:-1024}"
      OPTIMIZED_ACCEPTANCE="${OPTIMIZED_ACCEPTANCE:-valid_prediction_mc_letter}"
      ANSWER_FINALIZER_MODE="${ANSWER_FINALIZER_MODE:-when_needed}"
      ANSWER_FINALIZER_MAX_NEW_TOKENS="${ANSWER_FINALIZER_MAX_NEW_TOKENS:-32}"
      LT_BENCHMARK_TOTAL=1500
      ;;
    mmmu)
      PATH_TO_DATA="${PATH_TO_DATA:-${LT_DATA_ROOT}/MMMU-val-single-image}"
      DATASET_SPLIT="${DATASET_SPLIT:-validation}"
      MAX_NEW_TOKENS="${MAX_NEW_TOKENS:-1024}"
      OPTIMIZED_ACCEPTANCE="${OPTIMIZED_ACCEPTANCE:-valid_prediction_mc_letter}"
      ANSWER_FINALIZER_MODE="${ANSWER_FINALIZER_MODE:-off}"
      ANSWER_FINALIZER_MAX_NEW_TOKENS="${ANSWER_FINALIZER_MAX_NEW_TOKENS:-32}"
      LT_BENCHMARK_TOTAL=857
      ;;
    logicvista)
      PATH_TO_DATA="${PATH_TO_DATA:-${LT_DATA_ROOT}/LogicVista}"
      DATASET_SPLIT="${DATASET_SPLIT:-train}"
      MAX_NEW_TOKENS="${MAX_NEW_TOKENS:-1024}"
      OPTIMIZED_ACCEPTANCE="${OPTIMIZED_ACCEPTANCE:-valid_prediction_pairwise}"
      ANSWER_FINALIZER_MODE="${ANSWER_FINALIZER_MODE:-off}"
      ANSWER_FINALIZER_MAX_NEW_TOKENS="${ANSWER_FINALIZER_MAX_NEW_TOKENS:-32}"
      LT_BENCHMARK_TOTAL=448
      ;;
    realworldqa)
      PATH_TO_DATA="${PATH_TO_DATA:-${LT_DATA_ROOT}/RealWorldQA}"
      DATASET_SPLIT="${DATASET_SPLIT:-test}"
      MAX_NEW_TOKENS="${MAX_NEW_TOKENS:-1024}"
      OPTIMIZED_ACCEPTANCE="${OPTIMIZED_ACCEPTANCE:-valid_prediction_pairwise}"
      ANSWER_FINALIZER_MODE="${ANSWER_FINALIZER_MODE:-off}"
      ANSWER_FINALIZER_MAX_NEW_TOKENS="${ANSWER_FINALIZER_MAX_NEW_TOKENS:-32}"
      LT_BENCHMARK_TOTAL=765
      ;;
    hallusionbench)
      PATH_TO_DATA="${PATH_TO_DATA:-${LT_DATA_ROOT}/HallusionBench}"
      DATASET_SPLIT="${DATASET_SPLIT:-image}"
      MAX_NEW_TOKENS="${MAX_NEW_TOKENS:-256}"
      OPTIMIZED_ACCEPTANCE="${OPTIMIZED_ACCEPTANCE:-valid_prediction_pairwise}"
      ANSWER_FINALIZER_MODE="${ANSWER_FINALIZER_MODE:-off}"
      ANSWER_FINALIZER_MAX_NEW_TOKENS="${ANSWER_FINALIZER_MAX_NEW_TOKENS:-32}"
      LT_BENCHMARK_TOTAL=951
      ;;
    scienceqa)
      PATH_TO_DATA="${PATH_TO_DATA:-${LT_DATA_ROOT}/ScienceQA-IMG}"
      DATASET_SPLIT="${DATASET_SPLIT:-test}"
      MAX_NEW_TOKENS="${MAX_NEW_TOKENS:-512}"
      OPTIMIZED_ACCEPTANCE="${OPTIMIZED_ACCEPTANCE:-valid_prediction_mc_letter}"
      ANSWER_FINALIZER_MODE="${ANSWER_FINALIZER_MODE:-off}"
      ANSWER_FINALIZER_MAX_NEW_TOKENS="${ANSWER_FINALIZER_MAX_NEW_TOKENS:-32}"
      LT_BENCHMARK_TOTAL=2017
      ;;
    *)
      echo "Unknown BENCHMARK: ${BENCHMARK}" >&2
      return 2
      ;;
  esac

  TOTAL_EXAMPLES="${TOTAL_EXAMPLES:-${LT_BENCHMARK_TOTAL}}"
  export BENCHMARK PATH_TO_DATA DATASET_SPLIT MAX_NEW_TOKENS OPTIMIZED_ACCEPTANCE
  export ANSWER_FINALIZER_MODE ANSWER_FINALIZER_MAX_NEW_TOKENS TOTAL_EXAMPLES LT_BENCHMARK_TOTAL
}

